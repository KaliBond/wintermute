#!/usr/bin/env python3
"""
build_concordance.py — v1.2-Final (canonical) versus v1.0.1 (legacy comparator)
on every in-range society-year in data/v1.0_final_recompute/.

Run from the repository root:
    python praxis/concordance/build_concordance.py

Reads (never writes) the stored series and FG_corpus.csv. Both classifiers are
applied afresh to the stored raw scores. Stored regime labels in FG_corpus.csv
come from a third, older cascade (cams_framework_v2_4.py) and are reported
for context only. Nothing here changes a stored output or a lodged prediction.

Writes, next to this script:
    CLASSIFIER_CONCORDANCE.md
    concordance_rows.csv          one row per society-year, both labels
    confusion_matrix.csv
    disagreement_by_society.csv
"""
import hashlib
import os
import sys
from collections import Counter

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "praxis"))
import cams_praxis_calc as c  # noqa: E402

SERIES = os.path.join(ROOT, "data", "v1.0_final_recompute", "series")
FG = os.path.join(ROOT, "data", "v1.0_final_recompute", "FG_corpus.csv")
ORDER = ["Stable Adaptive", "Strained", "Local Node Failure", "Phantom Type II",
         "Systemic Crisis", "Freeze/Collapse", "Unclassified"]
SEVERE = {"Local Node Failure", "Phantom Type II", "Systemic Crisis", "Freeze/Collapse"}
# Anchor cases named in the build pack, plus well-known reference years.
ANCHORS = [("Hong Kong", 1943), ("Ukraine", 2022), ("Germany", 2024),
           ("Germany", 1933), ("Germany", 1945), ("Russia", 1917), ("Russia", 1991),
           ("United States", 2020), ("United Kingdom", 1940), ("Iran", 1979),
           ("Poland", 1939), ("Australia", 2026), ("China", 1967), ("Japan", 1945)]


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def compute(series_file):
    df = pd.read_csv(os.path.join(SERIES, series_file))
    rows = []
    for (soc, yr), d in df.groupby(["Society", "Year"]):
        d = d.set_index("Node").loc[c.NODES]
        C, K, S, A = (d[k].values for k in ("Coherence", "Capacity", "Stress", "Abstraction"))
        f = c.phase_space(C, K, S, A, "formal")
        g = c.phase_space(C, K, S, A, "v2.4-compat")
        rows.append({
            "Society": soc, "Year": int(yr), "series_file": series_file,
            "V_mean": round(f["V_mean"], 6), "V_min": round(f["V_min"], 6),
            "B_mean": round(f["B_mean"], 6), "lambda2": round(f["lambda2"], 6),
            "s_min": round(f["s_min"], 6),
            "v1_2_final": c.classify(f, c.CANONICAL), "v1_0_1": c.classify(f, c.LEGACY),
            "v1_2_final_compat_act": c.classify(g, c.CANONICAL),
            "v1_0_1_compat_act": c.classify(g, c.LEGACY),
            "s_min_differs_by_activation_mode": abs(f["s_min"] - g["s_min"]) > 1e-9,
        })
    return rows


def md_table(df, index=True):
    cols = ([df.index.name or ""] if index else []) + [str(x) for x in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] + ["---:"] * (len(cols) - 1)) + "|"]
    for idx, r in df.iterrows():
        vals = ([str(idx)] if index else []) + [str(v) for v in r.values]
        out.append("| " + " | ".join(vals) + " |")
    return "\n".join(out)


def confusion(df):
    m = pd.crosstab(df["v1_2_final"], df["v1_0_1"]).reindex(index=ORDER, columns=ORDER, fill_value=0)
    m = m.loc[(m.sum(axis=1) > 0) | (m.sum(axis=0) > 0), :]
    m = m.loc[:, m.sum(axis=0) > 0]
    m.index.name = "v1.2-Final (rows) \\ v1.0.1 (cols)"
    return m


def kappa(df):
    po = (df.v1_2_final == df.v1_0_1).mean()
    a, b = df.v1_2_final.value_counts(normalize=True), df.v1_0_1.value_counts(normalize=True)
    pe = sum(a.get(k, 0) * b.get(k, 0) for k in set(a.index) | set(b.index))
    return po, (po - pe) / (1 - pe)


def main():
    fg = pd.read_csv(FG)
    ir = fg[fg.range_tier == "in_range"]
    rows = []
    for sf in sorted(ir.series_file.unique()):
        rows += compute(sf)
    df = pd.DataFrame(rows).merge(
        ir[["Society", "Year", "series_file", "tier", "regime"]].rename(columns={"regime": "stored_v2_4_label"}),
        on=["Society", "Year", "series_file"], how="left")
    assert len(df) == len(ir) == 6778, (len(df), len(ir))
    df["agree"] = df.v1_2_final == df.v1_0_1
    df.to_csv(os.path.join(HERE, "concordance_rows.csv"), index=False)

    prim = df[df.tier.isin(["canonical_ens", "cleaned_ens"])]
    assert not prim.duplicated(["Society", "Year"]).any()

    L = []
    w = L.append
    w("# Classifier concordance: JUNO v1.2-Final (canonical) versus v1.0.1 (legacy comparator)\n")
    w("Generated by `praxis/concordance/build_concordance.py`. Do not edit by hand; re-run the script.\n")
    w("## What this report is\n")
    w("Both classifiers were applied afresh to the stored raw scores of every in-range society-year in "
      "`data/v1.0_final_recompute/`. The two are separate instruments. This report counts where their labels "
      "coincide and where they do not. It does not translate one label set into the other, and it changes no "
      "stored output and no lodged prediction.\n")
    w("It says nothing about which classifier is right. Neither has been validated against independently "
      "scored outcomes. Agreement here is agreement between two rule sets on the same model-scored inputs.\n")
    w("## Inputs\n")
    w(f"- `data/v1.0_final_recompute/FG_corpus.csv` sha256 `{sha(FG)[:16]}…`")
    w(f"- {ir.series_file.nunique()} in-range series files under `data/v1.0_final_recompute/series/`")
    w(f"- Calculator: `{c.CALC_VERSION}`, activation mode `formal`")
    w(f"- **All in-range rows: {len(df):,} society-years** across {df.Society.nunique()} societies. "
      f"{int(df.duplicated(['Society', 'Year'], keep=False).sum()):,} of these rows are the same society-year "
      "scored in more than one series (different scoring runs), so they are not independent.")
    w(f"- **Primary ensemble subset: {len(prim):,} society-years** across {prim.Society.nunique()} societies "
      "(tiers `canonical_ens` and `cleaned_ens`), one row per society-year. Use this subset for any rate that "
      "is meant to describe societies and not scoring runs.\n")

    for name, d in (("All 6,778 in-range society-years", df), (f"Primary ensemble subset ({len(prim):,})", prim)):
        po, k = kappa(d)
        w(f"## {name}\n")
        w(f"- Same label: **{int(d.agree.sum()):,} of {len(d):,} ({po:.1%})**. Different label: "
          f"{int((~d.agree).sum()):,} ({1 - po:.1%}). Cohen's kappa {k:.3f}.")
        sev = (d.v1_2_final.isin(SEVERE) == d.v1_0_1.isin(SEVERE)).mean()
        w(f"- Agreement on the coarser question \"severe or not\" (severe = Local Node Failure, Phantom Type II, "
          f"Systemic Crisis or Freeze/Collapse, as the lodged register defines it): {sev:.1%}.\n")
        w("### Confusion matrix (counts)\n")
        w(md_table(confusion(d)) + "\n")
        w("### Label totals\n")
        tot = pd.DataFrame({"v1.2-Final": d.v1_2_final.value_counts(), "v1.0.1": d.v1_0_1.value_counts()}
                           ).reindex(ORDER).dropna(how="all").fillna(0).astype(int)
        tot["difference"] = tot["v1.2-Final"] - tot["v1.0.1"]
        tot.index.name = "Regime"
        w(md_table(tot) + "\n")
        w("### Disagreements by v1.2-Final regime\n")
        byr = d.groupby("v1_2_final").agg(n=("agree", "size"), disagree=("agree", lambda x: int((~x).sum())))
        byr["share"] = (byr.disagree / byr.n).map("{:.1%}".format)
        byr["v1.0.1 says instead (top)"] = [
            "; ".join(f"{k} {v}" for k, v in Counter(d[(d.v1_2_final == r) & ~d.agree].v1_0_1).most_common(3)) or "none"
            for r in byr.index]
        byr = byr.reindex([r for r in ORDER if r in byr.index]); byr.index.name = "v1.2-Final regime"
        w(md_table(byr) + "\n")
        w("### The most common disagreement cells\n")
        cells = Counter(zip(d[~d.agree].v1_2_final, d[~d.agree].v1_0_1)).most_common(8)
        cdf = pd.DataFrame([{"v1.2-Final": a, "v1.0.1": b, "society-years": n,
                             "share of disagreements": f"{n / max(1, (~d.agree).sum()):.1%}"} for (a, b), n in cells])
        w(md_table(cdf, index=False) + "\n")

    w("## Disagreements by society (primary ensemble subset)\n")
    bys = prim.groupby("Society").agg(years=("agree", "size"), disagree=("agree", lambda x: int((~x).sum())))
    bys["share"] = bys.disagree / bys.years
    bys = bys.sort_values("share", ascending=False)
    bys.to_csv(os.path.join(HERE, "disagreement_by_society.csv"))
    show = bys.copy(); show["share"] = show.share.map("{:.1%}".format)
    show["main cell (v1.2-Final / v1.0.1)"] = [
        (lambda cc: f"{cc[0][0][0]} / {cc[0][0][1]} ({cc[0][1]})" if cc else "none")(
            Counter(zip(prim[(prim.Society == s) & ~prim.agree].v1_2_final,
                        prim[(prim.Society == s) & ~prim.agree].v1_0_1)).most_common(1)) for s in show.index]
    w(md_table(show) + "\n")
    w(f"Range across societies: {bys.share.min():.1%} to {bys.share.max():.1%}; median {bys.share.median():.1%}. "
      "The full all-rows breakdown is in `concordance_rows.csv`.\n")

    confusion(df).to_csv(os.path.join(HERE, "confusion_matrix.csv"))

    w("## Why they disagree\n")
    w("The two cascades differ in four places (exact rules in `praxis/CLASSIFIER_SPECIFICATIONS.md`):\n")
    w("1. **Phantom Type II.** v1.2-Final fires on `s_min < −0.65` alone, after Systemic Crisis. v1.0.1 needs "
      "`3 ≤ V̄ ≤ 6 AND V_min < 0 AND s_min < −0.7`, and tests it before Systemic Crisis.")
    w("2. **Local Node Failure.** v1.2-Final: `V_min < 4.0`. v1.0.1: `V_min < 4.5 OR s_min < −0.75`.")
    w("3. **Stable Adaptive.** v1.2-Final needs four conditions (`V̄ > 10, V_min > 5.0, B̄ > 0.28, s_min > −0.25`). "
      "v1.0.1 needs two (`V̄ > 10, B̄ > 0.25`).")
    w("4. **Rounding.** 6 decimal places against 4.\n")

    w("## Consequences for anchor cases\n")
    w("Labels below are computed from the primary ensemble series where one exists. \"Stored label\" is what "
      "`FG_corpus.csv` records, produced by the older v2.4 cascade; it is shown for context and is not altered.\n")
    arows = []
    for soc, yr in ANCHORS:
        d = prim[(prim.Society == soc) & (prim.Year == yr)]
        note = "primary ensemble"
        if d.empty:
            d = df[(df.Society == soc) & (df.Year == yr)].head(1); note = "non-primary series"
        if d.empty:
            oor = fg[(fg.Society == soc) & (fg.Year == yr)]
            if not oor.empty:
                sf = oor.iloc[0].series_file
                r = [x for x in compute(sf) if x["Year"] == yr][0]
                arows.append({"Case": f"{soc} {yr}", "V̄": f"{r['V_mean']:.2f}", "V_min": f"{r['V_min']:.2f}",
                              "B̄": f"{r['B_mean']:.3f}", "s_min": f"{r['s_min']:.2f}",
                              "v1.2-Final": r["v1_2_final"], "v1.0.1": r["v1_0_1"],
                              "Stored label": oor.iloc[0].regime,
                              "Note": "OUT OF RANGE series: scores outside 1–10, not in the 6,778"})
            else:
                arows.append({"Case": f"{soc} {yr}", "V̄": "", "V_min": "", "B̄": "", "s_min": "",
                              "v1.2-Final": "not in corpus", "v1.0.1": "not in corpus", "Stored label": "", "Note": ""})
            continue
        r = d.iloc[0]
        arows.append({"Case": f"{soc} {yr}", "V̄": f"{r.V_mean:.2f}", "V_min": f"{r.V_min:.2f}",
                      "B̄": f"{r.B_mean:.3f}", "s_min": f"{r.s_min:.2f}", "v1.2-Final": r.v1_2_final,
                      "v1.0.1": r.v1_0_1, "Stored label": r.stored_v2_4_label,
                      "Note": note + ("" if r.agree else "; **classifiers differ**")})
    w(md_table(pd.DataFrame(arows), index=False) + "\n")

    w("## Activation reading at Capacity = Stress\n")
    n_s = int(df.s_min_differs_by_activation_mode.sum())
    ch = int(((df.v1_2_final != df.v1_2_final_compat_act) | (df.v1_0_1 != df.v1_0_1_compat_act)).sum())
    w(f"`s_min` differs between the `formal` and `v2.4-compat` activation modes in {n_s:,} of {len(df):,} "
      f"society-years. The number of regime labels that change, under either classifier: **{ch}**.\n")

    w("## Stored v2.4 labels, for context\n")
    st = df.copy()
    norm = {"Stable adaptive": "Stable Adaptive", "Systemic crisis": "Systemic Crisis"}
    st["stored"] = st.stored_v2_4_label.replace(norm)
    w(f"- Stored label equals the v1.2-Final label in {(st.stored == st.v1_2_final).mean():.1%} of the 6,778 rows.")
    w(f"- Stored label equals the v1.0.1 label in {(st.stored == st.v1_0_1).mean():.1%}.")
    w("- So three label sets exist for this corpus. Any figure quoted from a stored file must say which cascade "
      "produced it.\n")

    w("## Limits\n")
    w("- All inputs are model-scored. Concordance measures rule-set agreement, not accuracy.")
    w("- The 6,778 rows include repeated society-years from different scoring runs. Rates on all rows weight "
      "heavily re-scored societies more.")
    w("- Ukraine's series is out of the 1–10 range and is therefore outside the 6,778. Its row above is "
      "computed for information only.")
    w("- v1.2-Final thresholds were chosen by inspection of a 3,002 society-year blind corpus "
      "(`juno/JUNO_v1.2-Final_Formalism.md` section 6). The provenance of the v1.0.1 thresholds is not "
      "documented in this repository.")
    open(os.path.join(HERE, "CLASSIFIER_CONCORDANCE.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    po, k = kappa(df)
    print(f"rows {len(df)} agree {po:.4f} kappa {k:.3f} | primary {len(prim)} agree {kappa(prim)[0]:.4f} | "
          f"s_min mode diffs {n_s}, label changes {ch}")


if __name__ == "__main__":
    main()
