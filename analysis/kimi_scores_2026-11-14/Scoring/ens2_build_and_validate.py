lines = ["Entity,Year,Node,Coherence,Capacity,Stress,Abstraction"]
for q in QUARTERS:
    for n in NODES:
        c, k, s, a = scores[n][q]
        lines.append(f"{ENTITY},{q},{n},{c},{k},{s},{a}")

with open(OUT, "w", newline="") as f:
    f.write("\n".join(lines) + "\n")

# ---- validation ----
errors = []
with open(OUT) as f:
    rows = [ln.rstrip("\n") for ln in f if ln.strip()]
if rows[0] != "Entity,Year,Node,Coherence,Capacity,Stress,Abstraction":
    errors.append("bad header")
data = rows[1:]
if len(data) != 192:
    errors.append(f"row count {len(data)} != 192")
expected_seq = [(q, n) for q in QUARTERS for n in NODES]
for i, ln in enumerate(data):
    parts = ln.split(",")
    if len(parts) != 7:
        errors.append(f"line {i+2}: {len(parts)} fields")
        continue
    ent, yr, node, c, k, s, a = parts
    if ent != ENTITY: errors.append(f"line {i+2}: entity {ent}")
    if (yr, node) != expected_seq[i]:
        errors.append(f"line {i+2}: order {(yr,node)} != {expected_seq[i]}")
    for val in (c, k, s, a):
        if val == "NA":
            continue
        if not (val.isdigit() and 1 <= int(val) <= 10):
            errors.append(f"line {i+2}: bad metric {val}")
# adjacent-quarter move check (>=2) — informational, printed for protocol note
moves = []
node_idx = {n: i for i, n in enumerate(NODES)}
for n in NODES:
    for qi in range(1, len(QUARTERS)):
        prev = scores[n][QUARTERS[qi-1]]
        cur = scores[n][QUARTERS[qi]]
        for mi, m in enumerate(("C","K","S","A")):
            if abs(cur[mi] - prev[mi]) >= 2:
                moves.append(f"{n} {QUARTERS[qi-1]}->{QUARTERS[qi]} {m}: {prev[mi]}->{cur[mi]}")

print("errors:", errors if errors else "NONE")
print("rows:", len(data))
print("moves>=2 (must each have a fact anchor in protocol note):")
for m in moves:
    print("  ", m)
