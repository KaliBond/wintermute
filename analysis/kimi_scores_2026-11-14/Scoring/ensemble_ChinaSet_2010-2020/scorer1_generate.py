METRICS = ["C", "K", "S", "A"]

def main():
    import csv, os
    outdir = os.path.dirname(os.path.abspath(__file__))
    raw_path = os.path.join(outdir, "scorer1_raw.csv")
    status_path = os.path.join(outdir, "scorer1_status.csv")

    rows = []
    status_rows = []
    n_na = 0
    for entity in ENTITY_ORDER:
        for year in YEARS:
            for node in NODES:
                vals = SCORES[entity][node][year]
                rows.append([entity, year, node] + list(vals))
                for v in vals:
                    if v == "NA":
                        n_na += 1
                # status per metric
                if year == 2010:
                    st = ["New_Evidence"] * 4
                else:
                    prev = SCORES[entity][node][year - 1]
                    st = []
                    for i in range(4):
                        if vals[i] == "NA" and prev[i] == "NA":
                            st.append("Carried_Forward")
                        elif vals[i] != prev[i]:
                            st.append("New_Evidence")
                        elif year in EXAMINED[entity]:
                            st.append("Reaffirmed")
                        else:
                            st.append("Carried_Forward")
                status_rows.append([entity, year, node] + st)

    # validation
    assert len(rows) == 704, f"row count {len(rows)} != 704"
    for r in rows:
        assert r[2] in NODES and NODES.index(r[2]) == (NODES.index(r[2]))
        for v in r[3:]:
            assert v == "NA" or (isinstance(v, int) and 1 <= v <= 10), f"bad value {v} in {r}"
    # CATL 2010 all NA
    for node in NODES:
        assert SCORES["CATL"][node][2010] == NA4
    # entity order + year order + node order spot check
    expected_keys = [(e, y, n) for e in ENTITY_ORDER for y in YEARS for n in NODES]
    actual_keys = [(r[0], r[1], r[2]) for r in rows]
    assert actual_keys == expected_keys

    with open(raw_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Entity", "Year", "Node", "Coherence", "Capacity", "Stress", "Abstraction"])
        w.writerows(rows)
    with open(status_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Entity", "Year", "Node", "C_status", "K_status", "S_status", "A_status"])
        w.writerows(status_rows)

    # report cells needing fact anchors: score <5, >8, or move >=2 vs prior year
    print(f"rows written: {len(rows)} (expect 704); NA cells: {n_na} (expect 32 = CATL 2010)")
    print("\n--- cells <5 or >8 ---")
    for entity in ENTITY_ORDER:
        for year in YEARS:
            for node in NODES:
                vals = SCORES[entity][node][year]
                if vals == NA4:
                    continue
                for i, m in enumerate(METRICS):
                    v = vals[i]
                    if v != "NA" and (v < 5 or v > 8):
                        print(f"{entity} {year} {node} {m}={v}")
    print("\n--- moves >=2 vs prior year ---")
    for entity in ENTITY_ORDER:
        for node in NODES:
            for year in YEARS[1:]:
                cur = SCORES[entity][node][year]
                prev = SCORES[entity][node][year - 1]
                for i, m in enumerate(METRICS):
                    if cur[i] == "NA" or prev[i] == "NA":
                        continue
                    if abs(cur[i] - prev[i]) >= 2:
                        print(f"{entity} {year} {node} {m}: {prev[i]} -> {cur[i]}")

if __name__ == "__main__":
    main()
