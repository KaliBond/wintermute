# ---- validation ----
def is_score(x):
    return (isinstance(x, str) and x == "NA") or (isinstance(x, int) and 1 <= x <= 10)

problems = []
for e in ENTITIES:
    for n in NODES:
        row = scores[e][n]
        if len(row) != 11:
            problems.append(f"{e}/{n}: {len(row)} years")
        for i, y in enumerate(YEARS):
            for v in row[i]:
                if not is_score(v):
                    problems.append(f"{e}/{n}/{y}: bad value {v}")
        # flag >=2 moves and <5/>8 cells for the audit trail
        for i in range(1, 11):
            for j, m in enumerate("CKSA"):
                a, b = row[i-1][j], row[i][j]
                if a != NA and b != NA and abs(a-b) >= 2:
                    problems.append(f"MOVE>=2 {e}/{n}/{YEARS[i-1]}->{YEARS[i]} {m}: {a}->{b}")
        for i, y in enumerate(YEARS):
            for j, m in enumerate("CKSA"):
                if row[i][j] != NA and (row[i][j] < 5 or row[i][j] > 8):
                    problems.append(f"EXTREME {e}/{n}/{y} {m}={row[i][j]}")

if problems:
    print("VALIDATION FLAGS (need anchors in note):")
    for p in problems:
        print(" ", p)
else:
    print("No extreme/move flags.")

# ---- write CSV ----
out = "scorer2_raw.csv"
with open(out, "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["Entity", "Year", "Node", "Coherence", "Capacity", "Stress", "Abstraction"])
    nrows = 0
    for e in ENTITIES:
        for y in YEARS:
            for n in NODES:
                c, k, s, a = scores[e][n][y - 2010]
                w.writerow([e, y, n, c, k, s, a])
                nrows += 1
print(f"Wrote {out}: {nrows} data rows")
